#[test]
fn str_matches_python_str_and_repr() {
    for (x, want) in STR {
        same(&py_str(*x), want, &format!("str({x:?})"));
    }
}

#[test]
fn fixed_matches_python_format_spec_f() {
    for (prec, table) in [(0, FIXED0), (1, FIXED1), (2, FIXED2), (3, FIXED3)] {
        for (x, want) in table {
            same(&fixed(*x, prec), want, &format!("f\"{{{x:?}:.{prec}f}}\""));
        }
    }
}

#[test]
fn fixed_rounds_the_exact_binary_value_half_to_even() {
    // Ties only occur for values exactly representable in binary.
    assert_eq!(fixed(0.5, 0), "0");
    assert_eq!(fixed(1.5, 0), "2");
    assert_eq!(fixed(2.5, 0), "2");
    assert_eq!(fixed(0.125, 2), "0.12");
    // 2.675 is below the tie in binary, so it rounds down.
    assert_eq!(fixed(2.675, 2), "2.67");
}

#[test]
fn general_matches_python_format_spec_g() {
    for (x, want) in GENERAL {
        same(&general(*x), want, &format!("f\"{{{x:?}:g}}\""));
    }
}

#[test]
fn percent_matches_python_format_spec_percent() {
    for (x, want) in PERCENT0 {
        same(&percent(*x, 0), want, &format!("f\"{{{x:?}:.0%}}\""));
    }
    for (x, want) in PERCENT1 {
        same(&percent(*x, 1), want, &format!("f\"{{{x:?}:.1%}}\""));
    }
}

#[test]
fn comma_fixed_matches_python_format_spec_comma_f() {
    for (prec, x, want) in COMMA {
        same(
            &comma_fixed(*x, *prec),
            want,
            &format!("f\"{{{x:?}:,.{prec}f}}\""),
        );
    }
}

/// Found by comparing 520,000 random floats with CPython. Rust's shortest-digit output picks a
/// different last digit when two shortest candidates both read back as the same float; Python
/// picks the one closest to the true value.
#[test]
fn str_picks_the_closest_of_two_equally_short_candidates() {
    assert_eq!(py_str(-109654900867286.12), "-109654900867286.12");
    assert_eq!(py_str(-2248632210524015.2), "-2248632210524015.2");
    assert_eq!(py_str(-1901340154952494.2), "-1901340154952494.2");
}
