/// The straight line between the two rows around `t_c` of one column; `None` outside the table.
fn at(table: &[(f64, f64)], t_c: f64, column: usize) -> Option<f64> {
    let x = t_c - TABLE_LOW_C;
    if x.is_nan() || x < 0.0 || x > (table.len() - 1) as f64 {
        return None;
    }
    let i = floor(x) as usize;
    let pick = |r: &(f64, f64)| if column == 0 { r.0 } else { r.1 };
    if i + 1 >= table.len() {
        return Some(pick(&table[i]));
    }
    let f = x - i as f64;
    Some(pick(&table[i]) + f * (pick(&table[i + 1]) - pick(&table[i])))
}

/// The mole fraction of propane in the `LPG_mix` Cargo.
pub fn mix_propane_mole_fraction() -> f64 {
    let p = MIX_PROPANE_MASS_FRACTION / PROPANE_MOLAR_MASS;
    let b = (1.0 - MIX_PROPANE_MASS_FRACTION) / N_BUTANE_MOLAR_MASS;
    p / (p + b)
}

/// The saturated liquid density of an LPG Cargo at `t_c` (kg/m3); `None` for another Cargo or a
/// temperature outside the table.
pub fn liquid_density_kg_m3(cargo: &str, t_c: f64) -> Option<f64> {
    match cargo {
        "LPG_propane" => at(&PROPANE, t_c, 1),
        "LPG_butane" => at(&N_BUTANE, t_c, 1),
        "LPG_mix" => {
            let (p, b) = (at(&PROPANE, t_c, 1)?, at(&N_BUTANE, t_c, 1)?);
            Some(1.0 / (MIX_PROPANE_MASS_FRACTION / p + (1.0 - MIX_PROPANE_MASS_FRACTION) / b))
        }
        _ => None,
    }
}

/// The vapour pressure of an LPG Cargo at `t_c` (bar absolute); `None` as for the density.
pub fn vapour_pressure_bar(cargo: &str, t_c: f64) -> Option<f64> {
    match cargo {
        "LPG_propane" => at(&PROPANE, t_c, 0),
        "LPG_butane" => at(&N_BUTANE, t_c, 0),
        "LPG_mix" => {
            let x = mix_propane_mole_fraction();
            Some(x * at(&PROPANE, t_c, 0)? + (1.0 - x) * at(&N_BUTANE, t_c, 0)?)
        }
        _ => None,
    }
}

/// The temperature at which the vapour pressure of an LPG Cargo is `p_bar` absolute (C), the
/// inverse of [`vapour_pressure_bar`] on the same straight lines; `None` outside the table.
pub fn saturation_temperature_c(cargo: &str, p_bar: f64) -> Option<f64> {
    let rows = match cargo {
        "LPG_propane" => PROPANE.len(),
        "LPG_butane" => N_BUTANE.len(),
        "LPG_mix" => PROPANE.len().min(N_BUTANE.len()),
        _ => return None,
    };
    let mut lo = vapour_pressure_bar(cargo, TABLE_LOW_C)?;
    if p_bar.is_nan() || p_bar < lo {
        return None;
    }
    for i in 1..rows {
        let t = TABLE_LOW_C + i as f64;
        let hi = vapour_pressure_bar(cargo, t)?;
        if p_bar <= hi {
            return Some(t - 1.0 + (p_bar - lo) / (hi - lo));
        }
        lo = hi;
    }
    None
}

/// IGC 15.5.1: the loading limit LL = FL x rho_R / rho_L, with FL the filling limit, rho_R the
/// density at the reference temperature and rho_L the density at the loading temperature.
pub fn loading_limit(filling_limit: f64, rho_reference: f64, rho_loading: f64) -> f64 {
    filling_limit * rho_reference / rho_loading
}
