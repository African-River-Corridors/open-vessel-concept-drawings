//! Tug presets (issue #357, spec 0007 "Formations"): the pushers, tugs and ATB tugs of the research
//! note (docs/research/stern-and-tugs.md sec. 10) that print their power, size and propulsor. A
//! preset fills the tug inputs of a barge Formation, marked `reference`.
//!
//! Every figure is as the source prints it (the research note's table and the files it names in the
//! rule-source library, stern-tug/vessels/). Horsepower is converted at 0.7457 kW per hp (derived);
//! a total power over its units is the source's total. A diameter or draught the source does not
//! print is `None`. Where the source names no duct, an azimuth drive is run as ducted and a fixed
//! propeller as open, as `basis` says.

/// What kind of tug a preset is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TugKind {
    Pusher,
    Tug,
    AtbTug,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct TugPreset {
    pub id: &'static str,
    pub name: &'static str,
    pub kind: TugKind,
    pub loa_m: f64,
    pub beam_m: f64,
    pub draught_m: Option<f64>,
    /// The installed propulsion power of all units (kW).
    pub installed_power_kw: f64,
    pub propulsor_type: &'static str,
    pub propulsor_count: u32,
    pub propeller_diameter_m: Option<f64>,
    pub power_source: &'static str,
    /// The source file in the rule-source library, relative to stern-tug/.
    pub source: &'static str,
    /// How the preset reads the source, where it is not plain.
    pub basis: &'static str,
}

