"""The Unicode tables in the Rust core are what Python 3.12 itself says.

`crates/ovcd-core/src/pystr_tables.rs` is generated by `tools/gen_pystr_tables.py`. Risk stopped:
someone edits the table by hand, or the generator changes and the file is left behind, so the
Rust core's `isidentifier`, `isprintable` and `float()` drift from Python's.
"""
import importlib.util
import sys
import unicodedata
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("gen_pystr_tables", ROOT / "tools" / "gen_pystr_tables.py")
gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gen)


@pytest.mark.skipif(unicodedata.unidata_version != "15.0.0",
                    reason="the committed tables are Python 3.12's Unicode 15.0")
def test_the_committed_tables_are_what_the_generator_writes():
    assert gen.OUT.read_text(encoding="utf-8") == gen.render()


def test_the_tables_hold_the_cases_the_review_found():
    text = gen.OUT.read_text(encoding="utf-8")
    assert "IDENTIFIER_START" in text and "DECIMAL_ZEROS" in text
    assert "0x660" in text  # Arabic-Indic digits
