"""The calibration pass runs end to end and covers every case in cases.yaml.

It must never write into the repository: its outputs go to a folder the caller names.
"""
import yaml

from vessel_designer import calibration
from vessel_designer.calibration import CAL, report


def _snapshot(folder):
    # Every file under the folder, by its path in it: the folder has sub-folders (calibration/shipd).
    return {str(p.relative_to(folder)): (p.stat().st_mtime_ns, p.read_bytes())
            for p in sorted(folder.rglob("*")) if p.is_file()}


def test_report_covers_every_case():
    """Label: property
    """
    text = report()
    for c in yaml.safe_load((CAL / "cases.yaml").read_text(encoding="utf-8"))["dry_barge"]:
        assert c["id"] in text
    section3 = text.split("## 3.")[1].split("## 4.")[0]     # section 4 (held-out cases) has its own dashes
    assert "–" not in section3.split("| Ratio |")[1].replace("|---", "")
    # Every held-out case that cannot run yet is reported too.
    for c in yaml.safe_load((CAL / "cases.yaml").read_text(encoding="utf-8"))["not_yet_runnable_cases"]:
        assert c["id"] in text


def test_report_writes_nothing_into_the_repo():
    """Label: property
    """
    before = _snapshot(CAL)
    report()
    assert _snapshot(CAL) == before


def test_main_writes_results_and_factors_to_the_folder_it_is_given(tmp_path):
    """Label: property
    """
    before = _snapshot(CAL)
    calibration.main(tmp_path)
    assert _snapshot(CAL) == before
    assert (tmp_path / "results.md").read_text(encoding="utf-8") == report()
    assert (tmp_path / "factors.yaml").read_text(encoding="utf-8").startswith("# GENERATED by")
    assert yaml.safe_load((tmp_path / "factors.yaml").read_text(encoding="utf-8")) == \
        yaml.safe_load((CAL / "factors.yaml").read_text(encoding="utf-8"))


# --- Calibration Bands (issue #119): a warning, never a block ------------------------------------

import copy
import subprocess
import sys

import pytest

from vessel_designer.calibration import (BANDS, assess, github_warning, load_cases, warnings_for)

CONFIDENCES = ("high", "medium", "low")


def test_every_figure_has_a_band_for_every_confidence_with_its_basis():
    """Label: property
    """
    assert set(BANDS["bands"]) == {"lightship_t", "dwt_t", "bollard_pull_t", "installed_power_kw"}
    for figure, band in BANDS["bands"].items():
        assert set(band["pct"]) == set(CONFIDENCES), figure
        assert band["basis"].strip(), figure
    assert BANDS["bands"]["lightship_t"]["pct"] == {"high": 15.0, "medium": 20.0, "low": 30.0}
    assert BANDS["bands"]["dwt_t"]["pct"] == {"high": 7.5, "medium": 10.0, "low": 15.0}


def test_every_case_with_a_figure_has_a_band_and_its_basis():
    """Label: property
    """
    cases = load_cases()["dry_barge"]
    checks = assess()
    for c in cases:
        assert c["confidence"] in CONFIDENCES, c["id"]
        figures = [f for f in ("lightship_t", "dwt_t") if f in c["observed"]]
        for f in figures:
            got = [b for b in checks if b.case == c["id"] and b.figure == f]
            assert len(got) == 1, (c["id"], f)
            assert got[0].band_pct == BANDS["bands"][f]["pct"][c["confidence"]]
            assert got[0].confidence == c["confidence"]
            assert got[0].basis == BANDS["bands"][f]["basis"]


def test_the_report_shows_each_result_against_its_band_and_marks_cases_outside():
    """Label: property
    """
    text = report()
    assert "## Calibration Bands" in text and "in-sample" in text.lower()
    assert "warning only" in text.lower()
    outside = [b for b in assess() if not b.inside]
    assert outside, "the committed cases have a case outside its band; the test needs one"
    for b in outside:
        row = next(line for line in text.splitlines() if line.startswith(f"| {b.case} |")
                   and f"±{b.band_pct:g}" in line)
        assert "OUTSIDE" in row


def test_a_deliberately_moved_figure_fires_the_warning():
    """Label: property
    """
    cases = copy.deepcopy(load_cases())
    base = {(b.case, b.figure): b for b in assess(cases)}
    target = next(c for c in cases["dry_barge"] if c["id"] == "danube-barge-77")
    assert base[("danube-barge-77", "lightship_t")].inside
    target["observed"]["lightship_t"] *= 2          # publish twice the lightship: the model is -50 %
    moved = {(b.case, b.figure): b for b in assess(cases)}
    hit = moved[("danube-barge-77", "lightship_t")]
    assert not hit.inside and hit.err_pct < -30
    lines = warnings_for(assess(cases))
    mine = [w for w in lines if "danube-barge-77" in w and "lightship" in w.lower()]
    assert len(mine) == 1
    assert mine[0].startswith("::warning ")
    assert "outside" in mine[0] and "±20" in mine[0]


def test_a_warning_annotation_cannot_be_broken_by_its_text():
    """Label: property
    """
    line = github_warning("a 50 % miss\nsecond line\r", title="Calibration band")
    assert line == "::warning title=Calibration band::a 50 %25 miss%0Asecond line%0D"


def test_the_check_prints_warnings_and_still_exits_zero():
    """Label: property
    """
    out = subprocess.run([sys.executable, "-m", "vessel_designer.calibration", "--check"],
                         capture_output=True, text=True)
    assert out.returncode == 0, out.stderr
    from vessel_designer.calibration import (_assess_installed_power, _assess_propulsion, _assess_tank_barges,
                                             _assess_tanks)
    # One annotation for each result outside its band: the barge, tank (issue #292), tank barge (issue
    # #335), bollard pull (issue #351) and installed power (issue #353) results.
    every = assess() + _assess_tanks() + _assess_tank_barges() + _assess_propulsion() + _assess_installed_power()
    assert out.stdout.count("::warning ") == sum(1 for b in every if not b.inside)


