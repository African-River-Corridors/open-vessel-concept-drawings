"""The calibration pass runs end to end and covers every case in cases.yaml.

It must never write into the repository: its outputs go to a folder the caller names.
"""
import yaml

from vessel_designer import calibration
from vessel_designer.calibration import CAL, report


def _snapshot(folder):
    return {p.name: (p.stat().st_mtime_ns, p.read_bytes()) for p in sorted(folder.iterdir())}


def test_report_covers_every_case():
    """Label: property
    Parity: barge_capacity:bauxite/calibration/*, resistance:compute/calibration/*
    """
    text = report()
    for c in yaml.safe_load((CAL / "cases.yaml").read_text())["dry_barge"]:
        assert c["id"] in text
    assert "–" not in text.split("## 3.")[1].split("| Ratio |")[1].replace("|---", "")


def test_report_writes_nothing_into_the_repo():
    """Label: property
    Parity: none (file-system behaviour, no calculation input)
    """
    before = _snapshot(CAL)
    report()
    assert _snapshot(CAL) == before


def test_main_writes_results_and_factors_to_the_folder_it_is_given(tmp_path):
    """Label: property
    Parity: none (file-system behaviour, no calculation input)
    """
    before = _snapshot(CAL)
    calibration.main(tmp_path)
    assert _snapshot(CAL) == before
    assert (tmp_path / "results.md").read_text() == report()
    assert (tmp_path / "factors.yaml").read_text().startswith("# GENERATED by")
    assert yaml.safe_load((tmp_path / "factors.yaml").read_text()) == \
        yaml.safe_load((CAL / "factors.yaml").read_text())
