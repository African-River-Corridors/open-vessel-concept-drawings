"""Write `crates/ovcd-core/src/nonprintable.rs`: the code points Python's `str.isprintable` rejects.

    python3.12 tools/gen_nonprintable.py > crates/ovcd-core/src/nonprintable.rs

Python 3.12 (Unicode 15.0) is the frozen Python's version; run this with that version. `repr(str)`
escapes exactly these code points, plus the quote and backslash. They are the categories Cc, Cf,
Cs, Co, Cn, Zl, Zp and Zs, except the ASCII space.
"""
import sys
import unicodedata

assert sys.version_info[:2] == (3, 12), "run with Python 3.12 (the frozen Python)"
ranges = []
for cp in range(0x110000):
    if not chr(cp).isprintable():
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
print("//! Generated by `tools/gen_nonprintable.py` (Python %d.%d, Unicode %s). Do not edit."
      % (sys.version_info[0], sys.version_info[1], unicodedata.unidata_version))
print("//! Code points for which Python's `str.isprintable()` is false, as inclusive ranges.")
print()
print("pub(crate) const NON_PRINTABLE: &[(u32, u32)] = &[")
for a, b in ranges:
    print("    (0x%X, 0x%X)," % (a, b))
print("];")
