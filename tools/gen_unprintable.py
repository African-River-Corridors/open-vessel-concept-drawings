#!/usr/bin/env python3
"""Generate crates/ovd-core/src/unprintable.rs: the code points Python's str.isprintable() rejects.

Run with Python 3.12 (Unicode 15.0), the version the Rust core follows:
    python3.12 tools/gen_unprintable.py > crates/ovd-core/src/unprintable.rs
"""
import sys
import unicodedata

ranges = []
start = None
for cp in range(0x110000):
    bad = not chr(cp).isprintable()
    if bad and start is None:
        start = cp
    elif not bad and start is not None:
        ranges.append((start, cp - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

out = sys.stdout
out.write("//! GENERATED by tools/gen_unprintable.py. Do not edit.\n")
out.write(f"//! Code points that Python's `str.isprintable()` rejects (Unicode {unicodedata.unidata_version}, ")
out.write(f"CPython {sys.version_info.major}.{sys.version_info.minor}).\n")
out.write("//! Python's `repr` writes each of these as an escape.\n\n")
out.write("/// Inclusive `(first, last)` ranges, sorted.\n")
out.write(f"pub(crate) const UNPRINTABLE: [(u32, u32); {len(ranges)}] = [\n")
for a, b in ranges:
    out.write(f"    (0x{a:04X}, 0x{b:04X}),\n")
out.write("];\n\n")
out.write("/// True when `c` is not printable in Python's sense.\n")
out.write("pub(crate) fn is_unprintable(c: char) -> bool {\n")
out.write("    let cp = c as u32;\n")
out.write("    UNPRINTABLE\n")
out.write("        .binary_search_by(|&(a, b)| {\n")
out.write("            if cp < a {\n                core::cmp::Ordering::Greater\n")
out.write("            } else if cp > b {\n                core::cmp::Ordering::Less\n")
out.write("            } else {\n                core::cmp::Ordering::Equal\n            }\n")
out.write("        })\n        .is_ok()\n}\n")
