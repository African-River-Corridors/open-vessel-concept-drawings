#!/usr/bin/env python3
"""Write `crates/ovd-core/src/pystr_tables.rs`: the Unicode tables behind `ovd_core::pystr`.

    python3.12 tools/gen_pystr_tables.py          # rewrite the file
    python3.12 tools/gen_pystr_tables.py --check  # exit 1 if the file is out of date

Python's `str.isidentifier`, `str.isprintable` and `float(str)` follow its own Unicode database.
The Rust core copies them exactly by reading the tables from Python itself. Use Python 3.12
(Unicode 15.0), the version the Rust core follows, or the tables drift from Python's answers.
Surrogates are left out: a Rust `char` cannot hold one.
"""
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "crates" / "ovd-core" / "src" / "pystr_tables.rs"
MAX = 0x110000


def runs(pred):
    """Inclusive (lo, hi) code point ranges where `pred` is true, surrogates excluded."""
    out, lo = [], None
    for cp in range(MAX):
        hit = pred(cp) and not 0xD800 <= cp <= 0xDFFF
        if hit and lo is None:
            lo = cp
        elif not hit and lo is not None:
            out.append((lo, cp - 1))
            lo = None
    if lo is not None:
        out.append((lo, MAX - 1))
    return out


def zero_digits():
    """First code point of every run of ten decimal digits (value 0..9 in order)."""
    zeros = []
    for cp in range(MAX):
        if unicodedata.decimal(chr(cp), None) == 0:
            for i in range(10):
                assert unicodedata.decimal(chr(cp + i), None) == i, hex(cp)
            zeros.append(cp)
    total = sum(1 for cp in range(MAX) if unicodedata.decimal(chr(cp), None) is not None)
    assert total == 10 * len(zeros), "a decimal digit outside a run of ten"
    return zeros


def pairs(name, doc, ranges):
    body = "".join(f"    (0x{lo:X}, 0x{hi:X}),\n" for lo, hi in ranges)
    return f"/// {doc}\n#[rustfmt::skip]\npub const {name}: [(u32, u32); {len(ranges)}] = [\n{body}];\n\n"


def render():
    zeros = zero_digits()
    text = (
        "// Generated by tools/gen_pystr_tables.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}). "
        "Do not edit by hand.\n\n"
    )
    text += pairs("IDENTIFIER_START", "Code points where `chr(cp).isidentifier()` is true.",
                  runs(lambda cp: chr(cp).isidentifier()))
    text += pairs("IDENTIFIER_CONTINUE",
                  "Code points where `('a' + chr(cp)).isidentifier()` is true.",
                  runs(lambda cp: ("a" + chr(cp)).isidentifier()))
    text += pairs("NOT_PRINTABLE", "Code points where `chr(cp).isprintable()` is false.",
                  runs(lambda cp: not chr(cp).isprintable()))
    body = "".join(f"    0x{z:X},\n" for z in zeros)
    text += ("/// First code point of each run of ten decimal digits, which `float()` reads as 0 to 9.\n"
             f"#[rustfmt::skip]\npub const DECIMAL_ZEROS: [u32; {len(zeros)}] = [\n{body}];\n")
    return text


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
