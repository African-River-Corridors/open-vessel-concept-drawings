#!/usr/bin/env python3
"""Fit the tank-barge lightship factor k (issue #330) and write calibration/tank_lightship.yaml.

    python3 tools/fit_tank_lightship.py            write the file
    python3 tools/fit_tank_lightship.py --check    fail when the file on disk is not what the fit writes

The fit is the algorithm: re-run it to regenerate. Inputs: `calibration/tank_lightship_inputs.yaml`
(the declared subset, the outfit coefficients), `calibration/cases.yaml` (the tank-barge records) and
`calibration/factors.yaml` (the box-barge block coefficient). Standard library plus PyYAML.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CAL = ROOT / "calibration"
OUT = CAL / "tank_lightship.yaml"
HEADER = (
    "# GENERATED by python3 tools/fit_tank_lightship.py from calibration/tank_lightship_inputs.yaml,\n"
    "# calibration/cases.yaml and calibration/factors.yaml. Do not edit: change the inputs and re-run.\n"
)


def tank_cases(doc: dict) -> list[dict]:
    found: list[dict] = []

    def walk(x):
        if isinstance(x, dict):
            if x.get("hold_type") == "tank" and "id" in x:
                found.append(x)
            for v in x.values():
                walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)

    walk(doc)
    return found


def outfit_t(volume_m3: float, coeff: dict, heating_kw: float = 0.0) -> float:
    return (volume_m3 * (coeff["pumps_t_per_m3"] + coeff["piping_t_per_m3"] + coeff["vents_gauging_t_per_m3"])
            + heating_kw * coeff["heating_t_per_kw"])


def implied(c: dict, cb: float, coeff: dict) -> dict | None:
    """The implied lightship and k of one record, or None when it has no deadweight, draught,
    depth or tank volume (a cargo capacity is not a deadweight)."""
    o = c["observed"]
    if "dwt_t" not in o or not c.get("draught_m") or not c.get("depth_m") or "tank_capacity_m3" not in o:
        return None
    L, B, D, T = c["loa_m"], c["beam_m"], c["depth_m"], c["draught_m"]
    rho = c.get("water_density_t_m3", 1.0)
    total = cb * L * B * T * rho - o["dwt_t"]
    hull = total - outfit_t(o["tank_capacity_m3"], coeff)
    return {"case": c["id"], "lightship_implied_t": round(total, 1), "hull_t": round(hull, 1),
            "k": hull / (L * B * D), "lbd": L * B * D, "outfit_t": total - hull}


def build() -> dict:
    inputs = yaml.safe_load((CAL / "tank_lightship_inputs.yaml").read_text(encoding="utf-8"))
    cases = tank_cases(yaml.safe_load((CAL / "cases.yaml").read_text(encoding="utf-8")))
    factors = yaml.safe_load((CAL / "factors.yaml").read_text(encoding="utf-8"))
    cb = factors["block_coefficient_box_barge_on_loa"]["value"]
    coeff = {k: v["value"] for k, v in inputs["outfit"].items()}
    by_id = {c["id"]: c for c in cases}
    missing = [i for i in inputs["fit_subset"] if i not in by_id]
    if missing:
        raise SystemExit(f"fit_subset names records that are not in cases.yaml: {missing}")
    fit_rows, held_rows = [], []
    for c in cases:
        row = implied(c, cb, coeff)
        if row is None:
            continue
        (fit_rows if c["id"] in inputs["fit_subset"] else held_rows).append(row)
    if len(fit_rows) != len(inputs["fit_subset"]):
        raise SystemExit("a case of fit_subset has no deadweight, draught, depth or tank volume")
    k = sum(r["k"] for r in fit_rows) / len(fit_rows)

    def err(r):
        pred = k * r["lbd"] + r["outfit_t"]
        return 100.0 * (pred - r["lightship_implied_t"]) / r["lightship_implied_t"]

    def pack(rows, with_err):
        out = []
        for r in rows:
            e = {"case": r["case"], "k_implied": round(r["k"], 4),
                 "lightship_implied_t": r["lightship_implied_t"]}
            if with_err:
                e["model_error_pct"] = round(err(r), 1)
            out.append(e)
        return out

    not_scored = inputs.get("not_scored", {})
    held_err = [abs(err(r)) for r in held_rows if r["case"] not in not_scored]
    fit_err = [abs(err(r)) for r in fit_rows]
    return {
        "tank_lightship_k_t_per_m3": {
            "value": round(k, 4),
            "n": len(fit_rows),
            "min": round(min(r["k"] for r in fit_rows), 4),
            "max": round(max(r["k"] for r in fit_rows), 4),
            "status": "estimate",
            "basis": ("Mean of the implied k of the declared subset. The lightship of each record is implied "
                      f"from its published deadweight at its draught with Cb = {cb} on LOA (box-barge value), "
                      "less the outfit; so k is an Estimate, not a measured lightship."),
            "block_coefficient_used": cb,
            "formula": "lightship = k x LOA x B x D + outfit; outfit = volume x (pumps + piping + vents) + kW x heating",
        },
        "outfit": {n: dict(v) for n, v in inputs["outfit"].items()},
        "fit_cases": pack(fit_rows, True),
        "held_out_cases": pack(held_rows, True),
        "not_scored": dict(not_scored),
        "model_error_in_sample_pct": {"mean_abs": round(sum(fit_err) / len(fit_err), 1),
                                      "max_abs": round(max(fit_err), 1)},
        "model_error_held_out_pct": {"n": len(held_err), "mean_abs": round(sum(held_err) / len(held_err), 1),
                                     "max_abs": round(max(held_err), 1)},
    }


def text() -> str:
    return HEADER + yaml.safe_dump(build(), sort_keys=False, width=100)


def main(argv: list[str]) -> int:
    new = text()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != new:
            print("calibration/tank_lightship.yaml is not what tools/fit_tank_lightship.py writes: re-run it")
            return 1
        print("tank_lightship.yaml is current")
        return 0
    OUT.write_text(new, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
