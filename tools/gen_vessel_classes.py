#!/usr/bin/env python3
"""Write `crates/ovcd-core/src/vessel_classes_generated.rs`: the Vessel Class list of the core.

    python3 tools/gen_vessel_classes.py          # rewrite the file
    python3 tools/gen_vessel_classes.py --check  # exit 1 if the file is out of date

`catalogue/vessel_classes.yaml` is the one source of the classes (issue #94). The core's list is
generated from it, so the two cannot drift, and `tests/test_gen_vessel_classes.py` fails when the
committed file is not what this script writes (the fast gate runs it). Edit `catalogue/raw/`, run
`tools/build_catalogue.py`, then this script.

The ids of the 12 classes the core held by hand before issue #94 stay valid as aliases (`LEGACY_IDS`).
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "catalogue" / "vessel_classes.yaml"
OUT = ROOT / "crates" / "ovcd-core" / "src" / "vessel_classes_generated.rs"

# The ids of the 12 classes the core listed by hand before issue #94, and the YAML class each now is.
# The Dutch 2011 wide motor vessel (`CEMT_VIa_motor_NL2011`) is the 135 m Rhine-max class `RWS-M12`.
LEGACY_IDS = {
    "CEMT_IV": "CEMT-IV",
    "CEMT_Va": "CEMT-Va",
    "CEMT_Vb": "CEMT-Vb",
    "CEMT_VIa": "CEMT-VIa",
    "CEMT_VIa_motor_NL2011": "RWS-M12",
    "CN_I_motor": "CN-I-MOTOR",
    "CN_II_motor": "CN-II-MOTOR",
    "CN_III_motor": "CN-III-MOTOR",
    "CN_IV_motor": "CN-IV-MOTOR",
    "CN_III_convoy_2ab": "CN-III-CONVOY-2x2",
    "CN_II_convoy_2ab": "CN-II-CONVOY-2x2",
    "CN_I_convoy_2ab": "CN-I-CONVOY-2x2",
}


def s(text) -> str:
    """A Rust string literal."""
    t = str(text if text is not None else "")
    t = t.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return f'"{t}"'


def num(x) -> str:
    return repr(float(x))


def rng(v) -> str:
    """`Option<(f64, f64)>` from a YAML scalar, two-item list, or null."""
    if v is None:
        return "None"
    lo, hi = (v if isinstance(v, list) else (v, v))
    return f"Some(({num(lo)}, {num(hi)}))"


def opt_int(v) -> str:
    return "None" if v is None else f"Some({int(v)})"


def row(c: dict) -> str:
    modes = ", ".join(s(m) for m in (c.get("cargo_modes") or []))
    return (
        "    ClassRow {\n"
        f"        id: {s(c['id'])},\n"
        f"        family: {s(c['family'])},\n"
        f"        region: {s(c['region'])},\n"
        f"        waters: {s(c['waters'])},\n"
        f"        formation: {s(c['formation'])},\n"
        f"        cargo_modes: &[{modes}],\n"
        f"        loa_m: {rng(c.get('loa_m'))},\n"
        f"        beam_m: {rng(c.get('beam_m'))},\n"
        f"        draught_m: {rng(c.get('draught_m'))},\n"
        f"        air_draft_m: {rng(c.get('air_draft_m'))},\n"
        f"        dwt_t: {rng(c.get('dwt_t'))},\n"
        f"        n_abreast: {opt_int(c.get('n_abreast'))},\n"
        f"        n_in_line: {opt_int(c.get('n_in_line'))},\n"
        f"        confidence: {s(c['confidence'])},\n"
        f"        source: {s(c.get('source'))},\n"
        f"        notes: {s(c.get('notes'))},\n"
        "    },\n"
    )


def render() -> str:
    classes = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))["classes"]
    ids = {c["id"] for c in classes}
    assert len(ids) == len(classes), "duplicate class ids"
    for old, new in LEGACY_IDS.items():
        assert new in ids, f"{old} -> {new}: no such class"
    out = ("// Generated by tools/gen_vessel_classes.py from catalogue/vessel_classes.yaml. "
           "Do not edit by hand.\n\n")
    out += f"#[rustfmt::skip]\npub static CLASSES: [ClassRow; {len(classes)}] = [\n"
    out += "".join(row(c) for c in classes) + "];\n\n"
    out += "/// The ids the core used before issue #94, and the class each now is.\n"
    out += f"pub static LEGACY_IDS: [(&str, &str); {len(LEGACY_IDS)}] = [\n"
    out += "".join(f"    ({s(o)}, {s(n)}),\n" for o, n in LEGACY_IDS.items()) + "];\n"
    return out


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
