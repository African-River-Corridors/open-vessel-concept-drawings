#!/usr/bin/env python3
"""Run the machinery layout (spec 0007, issue #352) against built ships (issue #365).

Each `stern_block_case` of `calibration/propulsion_cases.yaml` is built as a self-propelled Design
with the ship's LOA, beam, depth, propulsors and installed power, run with `ovcd run --json`, and the
modelled stern block (the end of the last machinery zone below deck) and aft peak are compared with the
lengths measured from the ship's general arrangement. Bands: `calibration/bands.yaml`, `stern_block_m`
(a miss is a warning, never a failure).

    python3 tools/stern_block_calibration.py <path to ovcd>            print the report
    python3 tools/stern_block_calibration.py <path to ovcd> --write    write calibration/stern_block_results.md
    python3 tools/stern_block_calibration.py <path to ovcd> --check    fail if the written file is stale

The report also gives the factor the run of the machinery (stern block less the aft peak) would still
need to match the ships: 1.00 means the layout is calibrated.
"""
import copy
import json
import math
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CAL = ROOT / "calibration"
BASE = ROOT / "crates/ovcd-format/tests/fixtures/dry_bulk_box_hold.vdesign"
BELOW_DECK = ("AFT PEAK", "SHAFT RUN", "DRIVE ROOM", "ENGINE ROOM", "GENSET ROOM", "BATTERY ROOM", "GVU ROOM")


def typed(inputs: dict, key: str, value) -> None:
    inputs[key] = {"value": value, "source": "typed"}


def run_case(ovcd: Path, base: dict, c: dict) -> dict:
    """The modelled aft peak and stern block of one case (m)."""
    d = copy.deepcopy(base)
    i = d["options"][0]["inputs"]
    typed(i, "formation", {"kind": "self_propelled"})
    typed(i, "length_overall_m", c["loa_m"])
    typed(i, "beam_m", c["beam_m"])
    typed(i, "moulded_depth_m", c["depth_m"])
    typed(i, "propulsor_type", c["run_as_type"])
    typed(i, "propulsor_count", c["n_engines"])
    typed(i, "propeller_diameter_m", c["propeller_diameter_m"])
    typed(i, "power_source", c["power_source"])
    typed(i, "installed_power_kw", float(c["installed_power_kw"]))
    with tempfile.TemporaryDirectory() as tmp:
        f = Path(tmp) / "case.vdesign"
        f.write_text(json.dumps(d))
        r = subprocess.run([str(ovcd), "run", "--json", str(f)], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"ovcd failed on {c['id']}: {r.stderr[-400:]}")
    zones = json.loads(r.stdout)["options"][0]["results"]["drawing"]["aft_arrangement"]["zones"]
    below = [z for z in zones if z[0].startswith(BELOW_DECK)]
    peak = next(z for z in below if z[0].startswith("AFT PEAK"))
    return {"aft_peak": peak[2], "stern_block": max(z[2] for z in below)}


def rms(xs):
    return math.sqrt(sum(x * x for x in xs) / len(xs))


def build(ovcd: Path) -> str:
    cases = yaml.safe_load((CAL / "propulsion_cases.yaml").read_text(encoding="utf-8"))["stern_block_case"]
    band = yaml.safe_load((CAL / "bands.yaml").read_text(encoding="utf-8"))["bands"]["stern_block_m"]
    base = json.loads(BASE.read_text(encoding="utf-8"))
    rows = []
    for c in cases:
        m = run_case(ovcd, base, c)
        obs = c["observed"]["stern_block_m"]
        err = m["stern_block"] - obs
        lim = float(band["pct"][c["confidence"]])
        rows.append({"c": c, "m": m, "obs": obs, "err": err, "pct": 100.0 * err / obs, "band": lim,
                     "inside": abs(100.0 * err / obs) <= lim})
    fit = [r for r in rows if r["c"]["fit"]]
    errs = [r["err"] for r in fit]
    inland = [r["err"] for r in fit if r["c"]["kind"] != "tug"]
    # What factor on the run (stern block less aft peak) would still match the ships, with the modelled aft peak.
    num = sum((r["obs"] - r["m"]["aft_peak"]) * (r["m"]["stern_block"] - r["m"]["aft_peak"]) for r in fit)
    den = sum((r["m"]["stern_block"] - r["m"]["aft_peak"]) ** 2 for r in fit)
    aps = [r["c"]["observed"]["aft_peak_m"] for r in fit if r["c"]["observed"]["aft_peak_m"] is not None]
    md = ["# Stern-block calibration (issue #365)", "",
          "GENERATED by `python3 tools/stern_block_calibration.py <ovcd> --write` from the `stern_block_case` "
          "list of `calibration/propulsion_cases.yaml`. Do not edit.", "",
          "The machinery layout (spec 0007, #352) is run for each built ship, and the end of its last machinery "
          "space below deck is compared with the length measured from the ship's general arrangement (derived "
          "from the drawing, tolerance `tol_m`; band `stern_block_m`). The aft peak and the room allowance are "
          "fitted to these ships, so **the errors of the fitted ships are in-sample**. A miss is a warning only.", "",
          f"Fit set: {len(fit)} of {len(rows)} ships. Stern block error (model - measured): mean "
          f"{sum(errs) / len(errs):+.2f} m, RMS {rms(errs):.2f} m; inland ships only: mean "
          f"{sum(inland) / len(inland):+.2f} m, RMS {rms(inland):.2f} m. Measured aft peak: mean "
          f"{sum(aps) / len(aps):.2f} m (range {min(aps):.2f} to {max(aps):.2f} m, n {len(aps)}). "
          f"Factor still needed on the machinery run: {num / den:.2f} (1.00 = calibrated).", "",
          "| Ship | Kind | Sample | Conf. | LOA (m) | P (kW) | Aft peak meas. / model (m) | "
          "Stern block meas. (m) | model (m) | err (m) | err % | Band ± % | vs band |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        c = r["c"]
        ap = c["observed"]["aft_peak_m"]
        md.append(f"| {c['id']} | {c['kind']} | {'in-sample' if c['fit'] else 'not fitted'} | {c['confidence']} | "
                  f"{c['loa_m']:g} | {c['installed_power_kw']:g} | {'-' if ap is None else format(ap, '.2f')} / "
                  f"{r['m']['aft_peak']:.2f} | {r['obs']:.2f} | {r['m']['stern_block']:.2f} | {r['err']:+.2f} | "
                  f"{r['pct']:+.0f} | ±{r['band']:g} | {'inside' if r['inside'] else '**OUTSIDE**'} |")
    md += ["", "## Ships kept out of the fit", ""]
    md += [f"- **{r['c']['id']}**: {r['c']['excluded']}" for r in rows if not r["c"]["fit"]]
    inside = sum(r["inside"] for r in fit)
    md += ["", f"Inside the band: {inside} of {len(fit)} fitted ships.", ""]
    return "\n".join(md)


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__)
        return 2
    report = build(Path(args[0]))
    target = CAL / "stern_block_results.md"
    if "--write" in argv:
        target.write_text(report, encoding="utf-8")
        print("stern_block_calibration: wrote", target.name)
    elif "--check" in argv:
        if not target.exists() or target.read_text(encoding="utf-8") != report:
            print("stern_block_calibration: stale")
            return 1
        print("stern_block_calibration: up to date")
    else:
        print(report)
    for line in report.splitlines():
        if "**OUTSIDE**" in line:
            print(f"::warning title=Calibration band::{line.split('|')[1].strip()}: stern block outside its band")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
