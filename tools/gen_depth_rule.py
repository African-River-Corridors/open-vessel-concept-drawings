#!/usr/bin/env python3
"""Write `catalogue/depth_rule.md`: every Reference Vessel with a published moulded depth, with the
value of the default moulded-depth rule beside it (issue #120).

    python3 tools/gen_depth_rule.py          # rewrite the file
    python3 tools/gen_depth_rule.py --check  # exit 1 if the file is out of date

Moulded depth is keel to main deck at the side. The rule is in the built-in Defaults Profile
(`crates/ovcd-format/src/builtin_profile.json`, `depth_to_beam_ratio`): D = ratio x B, by Cargo
group. This script reads the ratios from that file and the vessels from
`catalogue/reference_vessels.yaml`, so the table cannot say anything the data does not.

A Reference Vessel carries no Cargo in the catalogue, so its group is worked out here from the cargo
modes of its Vessel Classes (`catalogue/vessel_classes.yaml`), in this order:

1. `gas` in the modes: gas.
2. Otherwise a liquid mode (`liquid`, `liquid_bulk`, `liquid_bulk_petroleum`) and no dry-bulk, container
   or general mode: liquid.
3. Otherwise any mode: dry bulk (the group also holds container).
4. No cargo mode (a tug or a pusher): no group, so the rule does not apply.

A vessel is *inland* if all its classes are inland waters (not river-sea or coastal). The ratio is
meant as the midpoint of the range of the inland and pushed vessels for dry bulk and liquid, and of all
vessels for gas (nearly all are sea-going), so the table gives the range both ways.

Where a vessel is a tug and a barge with a depth each, the barge (the hull that carries the cargo)
is the row, and the tug's depth is in the notes.
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "catalogue" / "depth_rule.md"
PROFILE = ROOT / "crates" / "ovcd-format" / "src" / "builtin_profile.json"
VESSELS = ROOT / "catalogue" / "reference_vessels.yaml"
CLASSES = ROOT / "catalogue" / "vessel_classes.yaml"

LIQUID = {"liquid", "liquid_bulk", "liquid_bulk_petroleum"}
DRY = {"dry_bulk", "container", "general"}
GROUP_NAMES = {"dry_bulk": "dry bulk, container", "liquid": "liquid", "gas": "gas"}


def group_of(modes: set) -> str | None:
    if "gas" in modes:
        return "gas"
    if modes & LIQUID and not modes & DRY:
        return "liquid"
    if modes:
        return "dry_bulk"
    return None


def figure(value, part: str | None):
    """The published figure of a hull: a number, or the barge's of a tug-and-barge pair."""
    if isinstance(value, dict):
        return value.get(part or "barge"), value.get("tug") if part is None else None
    return value, None


def rows():
    profile = json.loads(PROFILE.read_text(encoding="utf-8"))["inputs"]
    ratios = profile["depth_to_beam_ratio"]["default_by_cargo_group"]
    slender = profile["length_to_depth_ratio"]["soft"]["max"]
    classes = {c["id"]: c for c in yaml.safe_load(CLASSES.read_text(encoding="utf-8"))["classes"]}
    out = []
    for v in yaml.safe_load(VESSELS.read_text(encoding="utf-8"))["vessels"]:
        if v.get("depth_m") is None:
            continue
        modes = {m for c in v["classes"] for m in (classes[c]["cargo_modes"] or [])}
        formations = sorted({classes[c]["formation"] for c in v["classes"]})
        inland = all(classes[c]["waters"] == "inland" for c in v["classes"])
        group = group_of(modes)
        depth, tug_depth = figure(v["depth_m"], None)
        beam, tug_beam = figure(v.get("beam_m"), None)
        note = ""
        if tug_depth is not None:
            note = f"tug {tug_depth:g} m deep, {tug_beam:g} m beam"
        ratio = depth / beam if depth and beam else None
        rule = round(ratios[group] * beam, 3) if group and beam else None
        loa, _ = figure(v.get("loa_m"), None)
        out.append(dict(name=v["name"], formation=", ".join(formations), group=group, beam=beam,
                        inland=inland,
                        depth=depth, ratio=ratio, rule=rule, loa=loa, note=note,
                        slender=bool(loa and depth and loa / depth > slender)))
    return out, ratios, slender


def num(x, nd=2):
    return "–" if x is None else f"{x:.{nd}f}".rstrip("0").rstrip(".") if nd else f"{x:g}"


def render() -> str:
    data, ratios, slender = rows()
    lines = [
        "<!-- GENERATED by tools/gen_depth_rule.py from the built-in Defaults Profile and "
        "catalogue/reference_vessels.yaml - do not edit by hand -->",
        "# Default moulded depth: the rule against the Reference Vessels", "",
        "Moulded depth is keel to main deck at the side. When an Option leaves it out, it is the "
        "depth-to-beam ratio of the Cargo times the beam, to the millimetre (`depth_to_beam_ratio` in "
        "the Defaults Profile, which a copy may edit). A Cargo is in the dry-bulk group if its phase is "
        "dry bulk, and in the gas group if it is a liquefied gas (LNG, ethane, the LPGs). Container "
        "shares the dry-bulk ratio; the liquid group has no Cargo yet.", "",
        "| Group | Ratio D/B | Vessels | D/B range, all | Inland vessels | D/B range, inland |",
        "|---|---|---|---|---|---|",
    ]

    def span(rs):
        return f"{min(rs):.2f} to {max(rs):.2f}" if rs else "–"

    for g, name in GROUP_NAMES.items():
        rs = [r["ratio"] for r in data if r["group"] == g and r["ratio"] is not None]
        ri = [r["ratio"] for r in data if r["group"] == g and r["ratio"] is not None and r["inland"]]
        lines.append(f"| {name} | {ratios[g]:g} | {len(rs)} | {span(rs)} | {len(ri)} | {span(ri)} |")
    none = [r for r in data if r["group"] is None]
    lines += [
        "",
        f"The ranges are those of the vessels below, grouped by the rule in the header of "
        f"`tools/gen_depth_rule.py`; the ratios are the Defaults Profile's. {len(data)} Reference "
        f"Vessels have a published depth; {len(none)} carry no cargo (a tug or pusher), so the rule "
        f"does not apply to them. A **slender** mark: the published length over depth is above "
        f"{slender:g}, the soft limit.", "",
        "| Reference Vessel | Formation | Waters | Group | Beam (m) | Published depth (m) | D/B | Rule depth (m) | Rule minus published | Notes |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    order = {"dry_bulk": 0, "liquid": 1, "gas": 2, None: 3}
    for r in sorted(data, key=lambda r: (order[r["group"]], r["ratio"] if r["ratio"] is not None else 9, r["name"])):
        diff = "–"
        if r["rule"] is not None and r["depth"]:
            diff = f"{r['rule'] - r['depth']:+.2f} m ({(r['rule'] - r['depth']) / r['depth'] * 100:+.0f} %)"
        notes = "; ".join(x for x in (r["note"], "slender" if r["slender"] else "") if x)
        lines.append(
            f"| {r['name'].replace('|', '/')} | {r['formation']} | {'inland' if r['inland'] else 'sea-going'} | "
            f"{GROUP_NAMES.get(r['group'], 'none (no cargo)')} | {num(r['beam'])} | {num(r['depth'])} | "
            f"{num(r['ratio'])} | {num(r['rule'])} | {diff} | {notes} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
